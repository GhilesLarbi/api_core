/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
type Environment = 'PRODUCTION' | 'STAGING' | 'LOCAL'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const ENVIRONMENT = (process.env.ENVIRONMENT ?? 'LOCAL') as Environment

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const API_URL: Record<Environment, string> = {
  PRODUCTION: 'https://api.example.com',
  STAGING: 'https://api.staging.example.com',
  LOCAL: 'http://localhost:8000',
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const settings = {
  ENVIRONMENT,
  API_URL: API_URL[ENVIRONMENT],
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const define = {
  'import.meta.env.VITE_API_URL': JSON.stringify(settings.API_URL),
}
