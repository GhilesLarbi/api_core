import { useTranslation } from 'react-i18next'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const KINDS = {
  photo: ['jpg', 'jpeg', 'png', 'webp', 'avif', 'heic', 'heif', 'bmp', 'tiff'],
  video: ['mp4', 'm4v', 'mov'],
  voiceNote: ['m4a', 'mp3', 'wav', 'ogg', 'oga', 'weba'],
  recording: ['webm'],
} as const

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
type Kind = keyof typeof KINDS | 'file'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function kindOf(url: string): Kind {
  const extension = url.split('?')[0].split('.').pop()?.toLowerCase() ?? ''
  const found = Object.entries(KINDS).find(([, extensions]) =>
    (extensions as readonly string[]).includes(extension)
  )
  return (found?.[0] as Kind) ?? 'file'
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useAttachmentLabels() {
  const { t } = useTranslation('common')

  return function label(urls: string[]) {
    const kinds = urls.map(kindOf)
    const seen = new Map<Kind, number>()

    return kinds.map((kind) => {
      const total = kinds.filter((other) => other === kind).length
      const number = (seen.get(kind) ?? 0) + 1
      seen.set(kind, number)
      const name = t(`upload.kinds.${kind}`)
      return total > 1 ? t('upload.numbered', { name, number }) : name
    })
  }
}
