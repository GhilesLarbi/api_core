import * as React from 'react'

import { cn } from '@shared/ui/lib/utils'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export type JoinedSeat = {
  ss: boolean
  se: boolean
  es: boolean
  ee: boolean
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const JoinedSeatContext = React.createContext<JoinedSeat | null>(null)

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useJoinedSeat(): string | null {
  const seat = React.useContext(JoinedSeatContext)
  if (!seat) return null
  return cn(
    'rounded-none',
    'ring-inset',
    seat.ss && 'rounded-ss-[var(--joined-radius)]',
    seat.se && 'rounded-se-[var(--joined-radius)]',
    seat.es && 'rounded-es-[var(--joined-radius)]',
    seat.ee && 'rounded-ee-[var(--joined-radius)]'
  )
}
