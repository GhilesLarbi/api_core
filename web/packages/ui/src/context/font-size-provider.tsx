import { createContext, useContext, useEffect, useState } from 'react'

import { getCookie, removeCookie, setCookie } from '@shared/ui/lib/cookies'
import {
  FONT_SIZE_SCALE,
  fontSizes,
  type FontSize,
} from '@shared/ui/lib/font-sizes'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const FONT_SIZE_COOKIE_NAME = 'font-size'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const FONT_SIZE_COOKIE_MAX_AGE = 60 * 60 * 24 * 365

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
type FontSizeContextType = {
  fontSize: FontSize
  setFontSize: (fontSize: FontSize) => void
  resetFontSize: () => void
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const FontSizeContext = createContext<FontSizeContextType | null>(null)

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function FontSizeProvider({ children }: { children: React.ReactNode }) {
  const [fontSize, _setFontSize] = useState<FontSize>(() => {
    const saved = getCookie(FONT_SIZE_COOKIE_NAME)
    return fontSizes.includes(saved as FontSize)
      ? (saved as FontSize)
      : 'default'
  })

  useEffect(() => {
    document.documentElement.style.fontSize = FONT_SIZE_SCALE[fontSize]
  }, [fontSize])

  const setFontSize = (fontSize: FontSize) => {
    setCookie(FONT_SIZE_COOKIE_NAME, fontSize, FONT_SIZE_COOKIE_MAX_AGE)
    _setFontSize(fontSize)
  }

  const resetFontSize = () => {
    removeCookie(FONT_SIZE_COOKIE_NAME)
    _setFontSize('default')
  }

  return (
    <FontSizeContext value={{ fontSize, setFontSize, resetFontSize }}>
      {children}
    </FontSizeContext>
  )
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
// eslint-disable-next-line react-refresh/only-export-components
export const useFontSize = () => {
  const context = useContext(FontSizeContext)
  if (!context) {
    throw new Error('useFontSize must be used within a FontSizeProvider')
  }
  return context
}
