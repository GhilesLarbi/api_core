import { keepPreviousData, queryOptions } from '@tanstack/react-query'

import {
  type AppLoadTimes,
  type AvgTimeOnPlatform,
  type FeatureUsageOverview,
  type Finances,
  type GeneralErrors,
  type OnboardingFunnel,
  type RetentionOverview,
  type SubscriberChurn,
} from '@shared/ui/lib/dashboard-types'

import {
  buildAvgTime,
  buildChurn,
  buildFeatureUsage,
  buildFinances,
  buildGeneralErrors,
  buildLoadTimes,
  buildOnboarding,
  buildRetention,
} from './data'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export async function fetchChurn(
  startISO: string,
  endISO: string
): Promise<SubscriberChurn> {
  return buildChurn(startISO, endISO)
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const churnQueryOptions = (startISO: string, endISO: string) =>
  queryOptions({
    queryKey: ['admin', 'dashboard', 'churn', startISO, endISO] as const,
    queryFn: () => fetchChurn(startISO, endISO),
    placeholderData: keepPreviousData,
    retry: false,
    staleTime: 30 * 1000,
  })

