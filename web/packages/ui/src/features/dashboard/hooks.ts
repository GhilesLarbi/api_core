import { useQuery } from '@tanstack/react-query'

import { useDashboardRangeStore } from '@shared/ui/lib/date-range-store'

import {
  avgTimeQueryOptions,
  churnQueryOptions,
  featureUsageQueryOptions,
  financesQueryOptions,
  generalErrorsQueryOptions,
  loadTimesQueryOptions,
  onboardingQueryOptions,
  retentionQueryOptions,
} from './api'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useChurn() {
  const startISO = useDashboardRangeStore((state) => state.startISO)
  const endISO = useDashboardRangeStore((state) => state.endISO)
  return useQuery(churnQueryOptions(startISO, endISO))
}

