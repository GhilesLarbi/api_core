import { type ReactNode } from 'react'

import { cn } from '@shared/ui/lib/utils'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const TONES = {
  amber: 'from-warning to-chart-3',
  rose: 'from-destructive to-warning',
  violet: 'from-chart-4 to-chart-1',
  blue: 'from-chart-1 to-chart-4',
  emerald: 'from-success to-chart-2',
  ink: 'from-primary to-foreground',
} as const

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export type MetricIconTone = keyof typeof TONES

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
type MetricIconProps = {
  children: ReactNode
  tone?: MetricIconTone
  className?: string
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function MetricIcon({
  children,
  tone = 'amber',
  className,
}: MetricIconProps) {
  return (
    <span
      className={cn(
        'flex size-7 items-center justify-center rounded-[0.6rem] bg-gradient-to-br text-white',
        TONES[tone],
        className
      )}
    >
      {children}
    </span>
  )
}
