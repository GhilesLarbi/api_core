import { type ReactNode } from 'react'
import { type UseQueryResult } from '@tanstack/react-query'
import { AlertCircle } from 'lucide-react'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
type QuerySectionProps<T> = {
  query: UseQueryResult<T>
  skeleton: ReactNode
  children: (data: T) => ReactNode
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function QuerySection<T>({
  query,
  skeleton,
  children,
}: QuerySectionProps<T>) {
  if (query.isLoading) return <>{skeleton}</>
  if (query.isError || query.data === undefined) return <SectionError />
  return <>{children(query.data)}</>
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function SectionError() {
  return (
    <div className='border-destructive/40 text-destructive flex items-center gap-2 border border-dashed p-4 text-sm'>
      <AlertCircle className='size-4 shrink-0' />
      Couldn&apos;t load this section
    </div>
  )
}
