import {
  endOfDay,
  endOfMonth,
  startOfDay,
  startOfMonth,
  subDays,
  subMonths,
} from 'date-fns'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const DASHBOARD_MIN_DATE = new Date(2026, 4, 1)

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export type RangeValue = { start: Date; end: Date }

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export type RangePreset = {
  key: string
  label: string
  compute: () => RangeValue
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function clampStart(start: Date): Date {
  return start < DASHBOARD_MIN_DATE ? DASHBOARD_MIN_DATE : start
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function lastNDays(days: number): RangeValue {
  return {
    start: clampStart(startOfDay(subDays(new Date(), days - 1))),
    end: endOfDay(new Date()),
  }
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const RANGE_PRESETS: RangePreset[] = [
  {
    key: 'today',
    label: 'Today',
    compute: () => ({
      start: startOfDay(new Date()),
      end: endOfDay(new Date()),
    }),
  },
  {
    key: 'yesterday',
    label: 'Yesterday',
    compute: () => ({
      start: startOfDay(subDays(new Date(), 1)),
      end: endOfDay(subDays(new Date(), 1)),
    }),
  },
  { key: 'last_7_days', label: 'Last 7 days', compute: () => lastNDays(7) },
  { key: 'last_14_days', label: 'Last 14 days', compute: () => lastNDays(14) },
  { key: 'last_30_days', label: 'Last 30 days', compute: () => lastNDays(30) },
  { key: 'last_60_days', label: 'Last 60 days', compute: () => lastNDays(60) },
  { key: 'last_90_days', label: 'Last 3 months', compute: () => lastNDays(90) },
  {
    key: 'last_180_days',
    label: 'Last 6 months',
    compute: () => lastNDays(180),
  },
  {
    key: 'last_365_days',
    label: 'Last 12 months',
    compute: () => lastNDays(365),
  },
  {
    key: 'this_month',
    label: 'This month',
    compute: () => ({
      start: clampStart(startOfMonth(new Date())),
      end: endOfDay(new Date()),
    }),
  },
  {
    key: 'last_month',
    label: 'Last month',
    compute: () => {
      const previous = subMonths(new Date(), 1)
      return {
        start: clampStart(startOfMonth(previous)),
        end: endOfMonth(previous),
      }
    },
  },
  {
    key: 'all_time',
    label: 'All time',
    compute: () => ({ start: DASHBOARD_MIN_DATE, end: endOfDay(new Date()) }),
  },
]

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const DEFAULT_PRESET_KEY = 'last_30_days'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function presetByKey(key: string): RangePreset | undefined {
  return RANGE_PRESETS.find((preset) => preset.key === key)
}
