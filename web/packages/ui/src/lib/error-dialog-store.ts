import { AxiosError } from 'axios'
import { create } from 'zustand'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export type ApiErrorInfo = {
  errorType: string | null
  message: string
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function asString(value: unknown): string | null {
  return typeof value === 'string' && value.length > 0 ? value : null
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function parseApiError(error: unknown): ApiErrorInfo {
  if (error instanceof AxiosError) {
    const data = error.response?.data as
      { error_code?: unknown; message?: unknown; detail?: unknown } | undefined
    return {
      errorType: asString(data?.error_code),
      message:
        asString(data?.message) ??
        asString(data?.detail) ??
        asString(error.message) ??
        'Something went wrong.',
    }
  }
  if (error && typeof error === 'object') {
    const obj = error as { error_code?: unknown; message?: unknown }
    return {
      errorType: asString(obj.error_code),
      message: asString(obj.message) ?? 'Something went wrong.',
    }
  }
  if (typeof error === 'string') return { errorType: null, message: error }
  return { errorType: null, message: 'Something went wrong.' }
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
type ErrorDialogState = {
  error: ApiErrorInfo | null
  showError: (error: unknown) => void
  clearError: () => void
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const useErrorDialog = create<ErrorDialogState>((set) => ({
  error: null,
  showError: (error) => set({ error: parseApiError(error) }),
  clearError: () => set({ error: null }),
}))
