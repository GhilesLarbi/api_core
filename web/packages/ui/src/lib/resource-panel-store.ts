import { create } from 'zustand'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export type ResourcePanelState = {
  id: string | null
  isCreating: boolean
  isOpen: boolean
  select: (id: string | null) => void
  startCreate: () => void
  close: () => void
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function createResourcePanelStore() {
  return create<ResourcePanelState>()((set) => ({
    id: null,
    isCreating: false,
    isOpen: false,
    select: (id) => set({ id, isCreating: false, isOpen: true }),
    startCreate: () => set({ isCreating: true, isOpen: true }),
    close: () => set({ isOpen: false, isCreating: false }),
  }))
}
