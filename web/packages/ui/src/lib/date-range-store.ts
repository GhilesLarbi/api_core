import { create } from 'zustand'

import {
  DEFAULT_PRESET_KEY,
  presetByKey,
  type RangeValue,
} from '../components/date-range-picker/presets'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
type DashboardRangeState = {
  startISO: string
  endISO: string
  presetKey: string
  setPreset: (key: string) => void
  setCustom: (range: RangeValue) => void
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function toISO(range: RangeValue) {
  return {
    startISO: range.start.toISOString(),
    endISO: range.end.toISOString(),
  }
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const initial = presetByKey(DEFAULT_PRESET_KEY)!.compute()

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const useDashboardRangeStore = create<DashboardRangeState>((set) => ({
  ...toISO(initial),
  presetKey: DEFAULT_PRESET_KEY,
  setPreset: (key) => {
    const preset = presetByKey(key)
    if (!preset) return
    set({ ...toISO(preset.compute()), presetKey: key })
  },
  setCustom: (range) => set({ ...toISO(range), presetKey: 'custom' }),
}))
