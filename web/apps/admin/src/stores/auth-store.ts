import { create } from 'zustand'

import { getCookie, removeCookie, setCookie } from '@shared/ui/lib/cookies'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const ACCESS_TOKEN_COOKIE = 'admin_access_token'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const REFRESH_TOKEN_COOKIE = 'admin_refresh_token'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const ADMIN_COOKIE = 'admin'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const COOKIE_MAX_AGE = 60 * 60 * 24 * 30

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function readAdmin(): Admin | null {
  const raw = getCookie(ADMIN_COOKIE)
  if (!raw) return null
  try {
    return JSON.parse(raw) as Admin
  } catch {
    return null
  }
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
type AuthState = {
  accessToken: string | null
  refreshToken: string | null
  admin: Admin | null
  setSession: (data: {
    accessToken: string
    refreshToken: string
    admin: Admin
  }) => void
  setTokens: (data: { accessToken: string; refreshToken: string }) => void
  setAdmin: (admin: Admin) => void
  clear: () => void
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const useAuthStore = create<AuthState>()((set) => ({
  accessToken: getCookie(ACCESS_TOKEN_COOKIE) ?? null,
  refreshToken: getCookie(REFRESH_TOKEN_COOKIE) ?? null,
  admin: readAdmin(),

  setSession: ({ accessToken, refreshToken, admin }) => {
    setCookie(ACCESS_TOKEN_COOKIE, accessToken, COOKIE_MAX_AGE)
    setCookie(REFRESH_TOKEN_COOKIE, refreshToken, COOKIE_MAX_AGE)
    setCookie(ADMIN_COOKIE, JSON.stringify(admin), COOKIE_MAX_AGE)
    set({ accessToken, refreshToken, admin })
  },

  setTokens: ({ accessToken, refreshToken }) => {
    setCookie(ACCESS_TOKEN_COOKIE, accessToken, COOKIE_MAX_AGE)
    setCookie(REFRESH_TOKEN_COOKIE, refreshToken, COOKIE_MAX_AGE)
    set({ accessToken, refreshToken })
  },

  setAdmin: (admin) => {
    setCookie(ADMIN_COOKIE, JSON.stringify(admin), COOKIE_MAX_AGE)
    set({ admin })
  },

  clear: () => {
    removeCookie(ACCESS_TOKEN_COOKIE)
    removeCookie(REFRESH_TOKEN_COOKIE)
    removeCookie(ADMIN_COOKIE)
    set({ accessToken: null, refreshToken: null, admin: null })
  },
}))
