import { createFileRoute } from '@tanstack/react-router'
import z from 'zod'

import { Admins } from '@/features/admins'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const adminsSearchSchema = z.object({
  page: z.number().optional().catch(1),
  limit: z.number().optional().catch(10),
  q: z.string().optional().catch(undefined),
  sort_by: z
    .enum(['EMAIL', 'FIRST_NAME', 'LAST_NAME', 'CREATED_AT'])
    .optional()
    .catch('CREATED_AT'),
  sort_direction: z.enum(['ASC', 'DESC']).optional().catch('DESC'),
})

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export type AdminsSearch = z.infer<typeof adminsSearchSchema>

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const Route = createFileRoute('/_authenticated/admins/')({
  validateSearch: adminsSearchSchema,
  staticData: { permission: 'admins.read' },
  component: Admins,
})
