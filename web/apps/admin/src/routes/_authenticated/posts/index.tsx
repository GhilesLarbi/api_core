import { createFileRoute } from '@tanstack/react-router'
import z from 'zod'

import { Posts } from '@/features/posts'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const postsSearchSchema = z.object({
  page: z.number().optional().catch(1),
  limit: z.number().optional().catch(10),
  q: z.string().optional().catch(undefined),
  is_hidden: z.boolean().optional().catch(undefined),
  sort_by: z.enum(['TITLE', 'CREATED_AT']).optional().catch('CREATED_AT'),
  sort_direction: z.enum(['ASC', 'DESC']).optional().catch('DESC'),
})

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export type PostsSearch = z.infer<typeof postsSearchSchema>

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const Route = createFileRoute('/_authenticated/posts/')({
  validateSearch: postsSearchSchema,
  staticData: { permission: 'posts.read' },
  component: Posts,
})
