import {
  queryOptions,
  useMutation,
  useQuery,
  useQueryClient,
} from '@tanstack/react-query'

import { apiClient, ApiRoutes } from '@/lib/api-client'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function fetchPosts(
  params: PostsListParams
): Promise<Paginated<AdminPost>> {
  const { data } = await apiClient.get<Paginated<AdminPost>>(
    ApiRoutes.posts.list,
    { params }
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function updatePost(
  postId: string,
  payload: PostAdminUpdatePayload
): Promise<AdminPost> {
  const { data } = await apiClient.put<AdminPost>(
    ApiRoutes.posts.update(postId),
    payload
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function deletePost(postId: string): Promise<void> {
  await apiClient.delete(ApiRoutes.posts.delete(postId))
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const postsQueryOptions = (params: PostsListParams) =>
  queryOptions({
    queryKey: ['admin', 'posts', params] as const,
    queryFn: () => fetchPosts(params),
    retry: false,
    staleTime: 30 * 1000,
    placeholderData: (prev: Paginated<AdminPost> | undefined) => prev,
  })

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function usePosts(params: PostsListParams) {
  return useQuery(postsQueryOptions(params))
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function usePostsMutation<TVariables, TData>(
  mutationFn: (variables: TVariables) => Promise<TData>
) {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn,
    meta: { skipGlobalError: true },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['admin', 'posts'] })
    },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useUpdatePost() {
  return usePostsMutation(
    ({
      postId,
      payload,
    }: {
      postId: string
      payload: PostAdminUpdatePayload
    }) => updatePost(postId, payload)
  )
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useDeletePost() {
  return usePostsMutation(deletePost)
}
