import {
  queryOptions,
  useMutation,
  useQuery,
  useQueryClient,
} from '@tanstack/react-query'
import { useRouter } from '@tanstack/react-router'

import { useAuthStore } from '@/stores/auth-store'
import { apiClient, ApiRoutes } from '@/lib/api-client'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function fetchAdmins(
  params: AdminsListParams = {}
): Promise<Paginated<Admin>> {
  const { data } = await apiClient.get<Paginated<Admin>>(
    ApiRoutes.admins.list,
    { params }
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function createAdmin(payload: AdminCreatePayload): Promise<Admin> {
  const { data } = await apiClient.post<Admin>(ApiRoutes.admins.create, payload)
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function updateAdmin(
  adminId: string,
  payload: AdminProfileUpdatePayload
): Promise<Admin> {
  const { data } = await apiClient.put<Admin>(
    ApiRoutes.admins.update(adminId),
    payload
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function deleteAdmin(adminId: string): Promise<void> {
  await apiClient.delete(ApiRoutes.admins.delete(adminId))
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function resetAdminPassword(
  adminId: string,
  password: string
): Promise<Admin> {
  const { data } = await apiClient.put<Admin>(
    ApiRoutes.admins.password(adminId),
    { password }
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function replaceAdminPermissions(
  adminId: string,
  permissions: string[]
): Promise<Admin> {
  const { data } = await apiClient.put<Admin>(
    ApiRoutes.admins.permissions(adminId),
    { permissions }
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const adminsQueryOptions = (params: AdminsListParams) =>
  queryOptions({
    queryKey: ['admin', 'admins', params] as const,
    queryFn: () => fetchAdmins(params),
    retry: false,
    staleTime: 30 * 1000,
    placeholderData: (prev: Paginated<Admin> | undefined) => prev,
  })

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useAdmins(params: AdminsListParams) {
  return useQuery(adminsQueryOptions(params))
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function useAdminsMutation<TVariables>(
  mutationFn: (variables: TVariables) => Promise<Admin>
) {
  const queryClient = useQueryClient()
  const router = useRouter()
  return useMutation({
    mutationFn,
    meta: { skipGlobalError: true },
    onSuccess: (admin) => {
      queryClient.invalidateQueries({ queryKey: ['admin', 'admins'] })
      if (admin.id === useAuthStore.getState().admin?.id) {
        useAuthStore.getState().setAdmin(admin)
        queryClient.setQueryData(['admin', 'me'], admin)
        router.invalidate()
      }
    },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useCreateAdmin() {
  return useAdminsMutation(createAdmin)
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useUpdateAdmin() {
  return useAdminsMutation(
    ({
      adminId,
      payload,
    }: {
      adminId: string
      payload: AdminProfileUpdatePayload
    }) => updateAdmin(adminId, payload)
  )
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useDeleteAdmin() {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: deleteAdmin,
    meta: { skipGlobalError: true },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['admin', 'admins'] })
    },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useResetAdminPassword() {
  return useAdminsMutation(
    ({ adminId, password }: { adminId: string; password: string }) =>
      resetAdminPassword(adminId, password)
  )
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useReplaceAdminPermissions() {
  return useAdminsMutation(
    ({ adminId, permissions }: { adminId: string; permissions: string[] }) =>
      replaceAdminPermissions(adminId, permissions)
  )
}
