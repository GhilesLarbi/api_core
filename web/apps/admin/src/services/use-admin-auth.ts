import {
  queryOptions,
  useMutation,
  useQuery,
  useQueryClient,
} from '@tanstack/react-query'

import { useAuthStore } from '@/stores/auth-store'
import { apiClient, ApiRoutes } from '@/lib/api-client'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function fetchAdminMe(): Promise<Admin> {
  const { data } = await apiClient.get<Admin>(ApiRoutes.adminAuth.me)
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function loginAdmin(payload: {
  email: string
  password: string
}): Promise<AdminTokenResponse> {
  const form = new URLSearchParams()
  form.set('username', payload.email)
  form.set('password', payload.password)
  const { data } = await apiClient.post<AdminTokenResponse>(
    ApiRoutes.adminAuth.login,
    form
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function updateAdmin(payload: AdminUpdatePayload): Promise<Admin> {
  const { data } = await apiClient.put<Admin>(
    ApiRoutes.adminAuth.update,
    payload
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const adminMeQueryOptions = () =>
  queryOptions({
    queryKey: ['admin', 'me'] as const,
    queryFn: fetchAdminMe,
    retry: false,
    staleTime: 5 * 60 * 1000,
  })

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useAdminMe() {
  return useQuery(adminMeQueryOptions())
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useAdminLogin() {
  return useMutation({
    mutationFn: loginAdmin,
    meta: { skipGlobalError: true },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useUpdateAdmin() {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: updateAdmin,
    meta: { skipGlobalError: true },
    onSuccess: (admin) => {
      useAuthStore.getState().setAdmin(admin)
      queryClient.setQueryData(['admin', 'me'], admin)
    },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function fetchAdminSessions(
  params: { page?: number; size?: number } = {}
): Promise<SessionListResponse> {
  const { data } = await apiClient.get<SessionListResponse>(
    ApiRoutes.adminAuth.sessions,
    { params }
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function logoutAdminSessions(
  sessionIds: string[]
): Promise<SessionsLogoutResponse> {
  const { data } = await apiClient.post<SessionsLogoutResponse>(
    ApiRoutes.adminAuth.sessionsLogout,
    { session_ids: sessionIds }
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const adminSessionsQueryOptions = (
  params: { page?: number; size?: number } = {}
) =>
  queryOptions({
    queryKey: ['admin', 'sessions', params] as const,
    queryFn: () => fetchAdminSessions(params),
    retry: false,
    staleTime: 30 * 1000,
    placeholderData: (prev: SessionListResponse | undefined) => prev,
  })

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useAdminSessions(
  params: { page?: number; size?: number } = {}
) {
  return useQuery(adminSessionsQueryOptions(params))
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useLogoutAdminSessions() {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: logoutAdminSessions,
    meta: { skipGlobalError: true },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['admin', 'sessions'] })
    },
  })
}
