import {
  queryOptions,
  useMutation,
  useQuery,
  useQueryClient,
} from '@tanstack/react-query'

import { apiClient, ApiRoutes } from '@/lib/api-client'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function fetchUsers(params: UsersListParams): Promise<Paginated<User>> {
  const { data } = await apiClient.get<Paginated<User>>(ApiRoutes.users.list, {
    params,
  })
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function createUser(payload: UserAdminCreatePayload): Promise<User> {
  const { data } = await apiClient.post<User>(ApiRoutes.users.create, payload)
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function updateUser(
  userId: string,
  payload: UserAdminUpdatePayload
): Promise<User> {
  const { data } = await apiClient.put<User>(
    ApiRoutes.users.update(userId),
    payload
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function deleteUser(userId: string): Promise<void> {
  await apiClient.delete(ApiRoutes.users.delete(userId))
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const usersQueryOptions = (params: UsersListParams) =>
  queryOptions({
    queryKey: ['admin', 'users', params] as const,
    queryFn: () => fetchUsers(params),
    retry: false,
    staleTime: 30 * 1000,
    placeholderData: (prev: Paginated<User> | undefined) => prev,
  })

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useUsers(params: UsersListParams) {
  return useQuery(usersQueryOptions(params))
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function useUsersMutation<TVariables, TData>(
  mutationFn: (variables: TVariables) => Promise<TData>
) {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn,
    meta: { skipGlobalError: true },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['admin', 'users'] })
    },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useCreateUser() {
  return useUsersMutation(createUser)
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useUpdateUser() {
  return useUsersMutation(
    ({
      userId,
      payload,
    }: {
      userId: string
      payload: UserAdminUpdatePayload
    }) => updateUser(userId, payload)
  )
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useDeleteUser() {
  return useUsersMutation(deleteUser)
}
