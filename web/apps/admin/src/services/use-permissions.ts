import { queryOptions, useQuery } from '@tanstack/react-query'

import { apiClient, ApiRoutes } from '@/lib/api-client'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function fetchPermissionTree(): Promise<PermissionNode[]> {
  const { data } = await apiClient.get<PermissionNode[]>(
    ApiRoutes.permissions.list
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const permissionTreeQueryOptions = () =>
  queryOptions({
    queryKey: ['admin', 'permissions'] as const,
    queryFn: fetchPermissionTree,
    retry: false,
    staleTime: 60 * 60 * 1000,
    meta: { localized: true },
  })

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function usePermissionTree() {
  return useQuery(permissionTreeQueryOptions())
}
