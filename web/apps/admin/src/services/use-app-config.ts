import {
  queryOptions,
  useMutation,
  useQuery,
  useQueryClient,
} from '@tanstack/react-query'

import { apiClient, ApiRoutes } from '@/lib/api-client'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function fetchAppConfig(): Promise<AppConfig> {
  const { data } = await apiClient.get<AppConfig>(ApiRoutes.appConfig.get)
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function updateAppConfig(
  payload: AppConfigUpdatePayload
): Promise<AppConfig> {
  const { data } = await apiClient.put<AppConfig>(
    ApiRoutes.appConfig.update,
    payload
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const appConfigQueryOptions = () =>
  queryOptions({
    queryKey: ['admin', 'app-config'] as const,
    queryFn: fetchAppConfig,
    retry: false,
    staleTime: 30 * 1000,
  })

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useAppConfig() {
  return useQuery(appConfigQueryOptions())
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useUpdateAppConfig() {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: updateAppConfig,
    meta: { skipGlobalError: true },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['admin', 'app-config'] })
    },
  })
}
