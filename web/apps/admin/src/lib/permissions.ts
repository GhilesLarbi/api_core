import { useAuthStore } from '@/stores/auth-store'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
declare module '@tanstack/react-router' {
  interface StaticDataRouteOption {
    permission?: PermissionPath
  }
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const NO_PERMISSIONS: PermissionPath[] = []

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function can(permission: PermissionPath): boolean {
  return (
    useAuthStore.getState().admin?.permissions.includes(permission) ?? false
  )
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useCan(permission: PermissionPath): boolean {
  return useAuthStore(
    (state) => state.admin?.permissions.includes(permission) ?? false
  )
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function usePermissions(): PermissionPath[] {
  return useAuthStore((state) => state.admin?.permissions) ?? NO_PERMISSIONS
}
