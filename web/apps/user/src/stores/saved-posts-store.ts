import { create } from 'zustand'

import { getCookie, removeCookie, setCookie } from '@shared/ui/lib/cookies'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const SAVED_POSTS_COOKIE = 'saved_post_ids'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const COOKIE_MAX_AGE = 60 * 60 * 24 * 30

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function read(): string[] {
  const raw = getCookie(SAVED_POSTS_COOKIE)
  if (!raw) return []
  return raw.split(',').filter((id) => UUID.test(id))
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function commit(ids: string[]) {
  if (ids.length === 0) {
    removeCookie(SAVED_POSTS_COOKIE)
  } else {
    setCookie(SAVED_POSTS_COOKIE, ids.join(','), COOKIE_MAX_AGE)
  }
  return { ids }
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
type SavedPostsState = {
  ids: string[]
  toggle: (postId: string) => void
  forget: () => void
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const useSavedPostsStore = create<SavedPostsState>()((set) => ({
  ids: read(),

  toggle: (postId) =>
    set((state) =>
      commit(
        state.ids.includes(postId)
          ? state.ids.filter((id) => id !== postId)
          : [...state.ids, postId]
      )
    ),

  forget: () => set(() => commit([])),
}))

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function getSavedPostIds(): string[] {
  return read()
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function savedPostIdsHeader() {
  const postIds = getSavedPostIds()
  return postIds.length > 0 ? { 'X-Saved-Post-Ids': postIds.join(',') } : {}
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function toggleSavedPost(postId: string) {
  useSavedPostsStore.getState().toggle(postId)
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function forgetSavedPosts() {
  useSavedPostsStore.getState().forget()
}
