import { create } from 'zustand'

import { getCookie, removeCookie, setCookie } from '@shared/ui/lib/cookies'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const ACCESS_TOKEN_COOKIE = 'user_access_token'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const REFRESH_TOKEN_COOKIE = 'user_refresh_token'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const USER_COOKIE = 'user'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const COOKIE_MAX_AGE = 60 * 60 * 24 * 30

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function readUser(): User | null {
  const raw = getCookie(USER_COOKIE)
  if (!raw) return null
  try {
    return JSON.parse(raw) as User
  } catch {
    return null
  }
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
type AuthState = {
  accessToken: string | null
  refreshToken: string | null
  user: User | null
  setSession: (data: {
    accessToken: string
    refreshToken: string
    user: User
  }) => void
  clear: () => void
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const useAuthStore = create<AuthState>()((set) => ({
  accessToken: getCookie(ACCESS_TOKEN_COOKIE) ?? null,
  refreshToken: getCookie(REFRESH_TOKEN_COOKIE) ?? null,
  user: readUser(),

  setSession: ({ accessToken, refreshToken, user }) => {
    setCookie(ACCESS_TOKEN_COOKIE, accessToken, COOKIE_MAX_AGE)
    setCookie(REFRESH_TOKEN_COOKIE, refreshToken, COOKIE_MAX_AGE)
    setCookie(USER_COOKIE, JSON.stringify(user), COOKIE_MAX_AGE)
    set({ accessToken, refreshToken, user })
  },

  clear: () => {
    removeCookie(ACCESS_TOKEN_COOKIE)
    removeCookie(REFRESH_TOKEN_COOKIE)
    removeCookie(USER_COOKIE)
    set({ accessToken: null, refreshToken: null, user: null })
  },
}))
