import { profileQueryOptions } from '@/services/use-user'
import {
  queryOptions,
  useMutation,
  useQuery,
  useQueryClient,
} from '@tanstack/react-query'

import { useAuthStore } from '@/stores/auth-store'
import { apiClient, ApiRoutes } from '@/lib/api-client'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function updateUser(payload: UserUpdatePayload): Promise<User> {
  const { data } = await apiClient.put<User>(ApiRoutes.userAuth.update, payload)
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function changeUserPassword(
  payload: PasswordChangePayload
): Promise<UserTokenResponse> {
  const { data } = await apiClient.put<UserTokenResponse>(
    ApiRoutes.userAuth.changePassword,
    payload
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function requestUserEmailChange(
  payload: EmailChangePayload
): Promise<MessageResponse> {
  const { data } = await apiClient.post<MessageResponse>(
    ApiRoutes.userAuth.emailChange,
    payload
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function resendUserVerification(): Promise<MessageResponse> {
  const { data } = await apiClient.post<MessageResponse>(
    ApiRoutes.userAuth.resendVerification
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function deleteUserAccount(): Promise<MessageResponse> {
  const { data } = await apiClient.delete<MessageResponse>(
    ApiRoutes.userAuth.delete
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function fetchUserSessions(
  params: { page?: number; size?: number } = {}
): Promise<UserSessionListResponse> {
  const { data } = await apiClient.get<UserSessionListResponse>(
    ApiRoutes.userAuth.sessions,
    { params }
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function logoutUserSessions(
  sessionIds: string[]
): Promise<SessionsLogoutResponse> {
  const { data } = await apiClient.post<SessionsLogoutResponse>(
    ApiRoutes.userAuth.sessionsLogout,
    { session_ids: sessionIds }
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const userSessionsQueryOptions = (
  params: { page?: number; size?: number } = {}
) =>
  queryOptions({
    queryKey: ['user', 'sessions', params] as const,
    queryFn: () => fetchUserSessions(params),
    retry: false,
    staleTime: 30 * 1000,
    placeholderData: (prev: UserSessionListResponse | undefined) => prev,
  })

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useUpdateUser() {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: updateUser,
    meta: { skipGlobalError: true },
    onSuccess: (user) => {
      const { accessToken, refreshToken } = useAuthStore.getState()
      if (accessToken && refreshToken) {
        useAuthStore.getState().setSession({ accessToken, refreshToken, user })
      }
      queryClient.setQueryData(profileQueryOptions().queryKey, user)
    },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useChangeUserPassword() {
  return useMutation({
    mutationFn: changeUserPassword,
    meta: { skipGlobalError: true },
    onSuccess: (data) => {
      useAuthStore.getState().setSession({
        accessToken: data.access_token,
        refreshToken: data.refresh_token,
        user: data.user,
      })
    },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useRequestUserEmailChange() {
  return useMutation({
    mutationFn: requestUserEmailChange,
    meta: { skipGlobalError: true },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useResendUserVerification() {
  return useMutation({
    mutationFn: resendUserVerification,
    meta: { skipGlobalError: true },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useDeleteUserAccount() {
  return useMutation({
    mutationFn: deleteUserAccount,
    meta: { skipGlobalError: true },
    onSuccess: () => {
      useAuthStore.getState().clear()
    },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useUserSessions(params: { page?: number; size?: number } = {}) {
  return useQuery(userSessionsQueryOptions(params))
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useLogoutUserSessions() {
  const queryClient = useQueryClient()
  return useMutation({
    mutationFn: logoutUserSessions,
    meta: { skipGlobalError: true },
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: ['user', 'sessions'] })
    },
  })
}
