import {
  queryOptions,
  useMutation,
  useQuery,
  useQueryClient,
} from '@tanstack/react-query'

import { useAuthStore } from '@/stores/auth-store'
import {
  forgetSavedPosts,
  savedPostIdsHeader,
} from '@/stores/saved-posts-store'
import { apiClient, ApiRoutes } from '@/lib/api-client'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function loginUser(payload: {
  email: string
  password: string
}): Promise<UserTokenResponse> {
  const form = new URLSearchParams()
  form.set('username', payload.email)
  form.set('password', payload.password)
  const { data } = await apiClient.post<UserTokenResponse>(
    ApiRoutes.userAuth.login,
    form,
    { headers: savedPostIdsHeader() }
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function registerUser(
  payload: UserCreatePayload
): Promise<UserTokenResponse> {
  const { data } = await apiClient.post<UserTokenResponse>(
    ApiRoutes.userAuth.register,
    payload,
    { headers: savedPostIdsHeader() }
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function fetchProfile(): Promise<UserProfile> {
  const { data } = await apiClient.get<UserProfile>(ApiRoutes.userAuth.me)
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function forgotUserPassword(
  payload: PasswordForgotPayload
): Promise<MessageResponse> {
  const { data } = await apiClient.post<MessageResponse>(
    ApiRoutes.userAuth.forgotPassword,
    payload
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function resetUserPassword(
  payload: PasswordResetPayload
): Promise<UserTokenResponse> {
  const { data } = await apiClient.post<UserTokenResponse>(
    ApiRoutes.userAuth.resetPassword,
    payload
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const PROFILE_KEY = ['user', 'profile'] as const

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function profileQueryOptions() {
  return queryOptions({
    queryKey: PROFILE_KEY,
    queryFn: fetchProfile,
    retry: false,
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useProfile() {
  const signedIn = useAuthStore((state) => Boolean(state.accessToken))
  return useQuery({ ...profileQueryOptions(), enabled: signedIn })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function useSignedIn() {
  const queryClient = useQueryClient()

  return (token: UserTokenResponse) => {
    useAuthStore.getState().setSession({
      accessToken: token.access_token,
      refreshToken: token.refresh_token,
      user: token.user,
    })
    forgetSavedPosts()
    void queryClient.invalidateQueries({ queryKey: ['public', 'posts'] })
  }
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useUserLogin() {
  const signedIn = useSignedIn()

  return useMutation({
    mutationFn: loginUser,
    onSuccess: signedIn,
    meta: { skipGlobalError: true },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useUserRegister() {
  const signedIn = useSignedIn()

  return useMutation({
    mutationFn: registerUser,
    onSuccess: signedIn,
    meta: { skipGlobalError: true },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useForgotUserPassword() {
  return useMutation({
    mutationFn: forgotUserPassword,
    meta: { skipGlobalError: true },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useResetUserPassword() {
  return useMutation({
    mutationFn: resetUserPassword,
    meta: { skipGlobalError: true },
  })
}
