import {
  infiniteQueryOptions,
  keepPreviousData,
  queryOptions,
  useInfiniteQuery,
  useQuery,
} from '@tanstack/react-query'

import { apiClient, ApiRoutes } from '@/lib/api-client'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const POSTS_KEY = ['public', 'posts'] as const

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export const POSTS_PAGE_LIMIT = 12

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function publicPostsQueryOptions(params: PostListParams = {}) {
  return queryOptions({
    queryKey: [...POSTS_KEY, params] as const,
    queryFn: async () => {
      const { data } = await apiClient.get<Paginated<Post>>(
        ApiRoutes.publicPosts.list,
        { params }
      )
      return data
    },
    placeholderData: keepPreviousData,
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function publicPostsFeedOptions() {
  return infiniteQueryOptions({
    queryKey: [...POSTS_KEY, 'feed'] as const,
    queryFn: async ({ pageParam }) => {
      const { data } = await apiClient.get<Paginated<Post>>(
        ApiRoutes.publicPosts.list,
        { params: { page: pageParam, limit: POSTS_PAGE_LIMIT } }
      )
      return data
    },
    initialPageParam: 1,
    getNextPageParam: (last) =>
      last.page * last.limit < last.total ? last.page + 1 : undefined,
    placeholderData: keepPreviousData,
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function usePublicPostsFeed() {
  return useInfiniteQuery(publicPostsFeedOptions())
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function usePublicPosts(params: PostListParams = {}, enabled = true) {
  return useQuery({ ...publicPostsQueryOptions(params), enabled })
}
