import { POSTS_PAGE_LIMIT } from '@/services/use-public-posts'
import {
  keepPreviousData,
  useInfiniteQuery,
  useMutation,
  useQueryClient,
} from '@tanstack/react-query'

import { useAuthStore } from '@/stores/auth-store'
import { apiClient, ApiRoutes } from '@/lib/api-client'

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
const SAVED_POSTS_KEY = ['user', 'posts', 'saved'] as const

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function createPost(payload: PostCreatePayload): Promise<Post> {
  const { data } = await apiClient.post<Post>(
    ApiRoutes.userPosts.create,
    payload
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function savePost(postId: string): Promise<MessageResponse> {
  const { data } = await apiClient.post<MessageResponse>(
    ApiRoutes.userPosts.save(postId)
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function unsavePost(postId: string): Promise<MessageResponse> {
  const { data } = await apiClient.delete<MessageResponse>(
    ApiRoutes.userPosts.unsave(postId)
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
async function fetchSavedPosts(
  params: { page?: number; limit?: number } = {}
): Promise<Paginated<Post>> {
  const { data } = await apiClient.get<Paginated<Post>>(
    ApiRoutes.userPosts.saved,
    { params }
  )
  return data
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
function useInvalidatePosts() {
  const queryClient = useQueryClient()
  return () => {
    void queryClient.invalidateQueries({ queryKey: ['public', 'posts'] })
    void queryClient.invalidateQueries({ queryKey: SAVED_POSTS_KEY })
  }
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useCreatePost() {
  const invalidate = useInvalidatePosts()
  return useMutation({
    mutationFn: createPost,
    onSuccess: invalidate,
    meta: { skipGlobalError: true },
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useSavePost() {
  const invalidate = useInvalidatePosts()
  return useMutation({
    mutationFn: savePost,
    onSuccess: invalidate,
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useUnsavePost() {
  const invalidate = useInvalidatePosts()
  return useMutation({
    mutationFn: unsavePost,
    onSuccess: invalidate,
  })
}

/////////////////////////////////////////////////////////////////////////////////////////////////////////
/////////////////////////////////////////////////////////////////////////////////////////////////////////
export function useSavedPostsFeed() {
  const signedIn = useAuthStore((state) => Boolean(state.accessToken))
  return useInfiniteQuery({
    queryKey: [...SAVED_POSTS_KEY, 'feed'] as const,
    queryFn: ({ pageParam }) =>
      fetchSavedPosts({ page: pageParam, limit: POSTS_PAGE_LIMIT }),
    initialPageParam: 1,
    getNextPageParam: (last) =>
      last.page * last.limit < last.total ? last.page + 1 : undefined,
    placeholderData: keepPreviousData,
    enabled: signedIn,
  })
}
